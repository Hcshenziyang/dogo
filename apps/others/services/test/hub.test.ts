import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { fixture } from './helpers.ts';

test('v2 durable conversation, offline turns, idempotency and same-device ownership', async t => {
  const f = await fixture(t);
  const mac = (op: string, args = {}) => f.mac.request<any>('/v2/hub', 'POST', { op, args });
  const phone = (op: string, args = {}) => f.phone.request<any>('/v2/hub', 'POST', { op, args });
  const instance = randomUUID(), projectId = randomUUID();
  await mac('advertise', { instance, name: 'Fixture Mac', ready: true, projects: [{ id: projectId, name: 'fixture', available: true }] });
  const input = { requestId: randomUUID(), target: 'mac', projectId, title: 'Fixture', prompt: 'First turn' };
  const first = await phone('create', input);
  assert.equal(first.status, 'queued');
  assert.equal((await phone('create', input)).id, first.id);
  await assert.rejects(phone('create', { ...input, prompt: 'changed' }), /different content/);
  const items = (await phone('snapshot')).items;
  const session = items.find((i: any) => i.id === first.sessionId);
  assert.equal(items.find((i: any) => i.type === 'device').online, false);
  const executionId = randomUUID();
  await mac('claim', { id: first.id, executionId });
  await assert.rejects(mac('claim', { id: first.id, executionId: randomUUID() }), /already claimed/);
  const finish = { id: first.id, executionId, status: 'succeeded', result: 'Answer 1' };
  await mac('finish', finish); await mac('finish', finish);
  await mac('append', { sessionId: session.id, messages: [{ id: 'm1', role: 'assistant', text: 'Answer 1', seq: 0, at: 1 }] });
  const second = await phone('send', { sessionId: session.id, requestId: randomUUID(), prompt: 'Continue' });
  assert.equal(second.sessionId, first.sessionId);
  assert.equal((await phone('history', { sessionId: session.id })).messages[0].text, 'Answer 1');
  await assert.rejects(mac('session', { id: session.id, nativeId: randomUUID(), instance, title: 'moved', projectId, state: 'idle', cursor: 1 }), /cannot migrate/);
  await assert.rejects(f.win.request('/v2/hub', 'POST', { op: 'history', args: { sessionId: session.id } }), /not found/);
  await assert.rejects(phone('claim', { id: second.id, executionId: randomUUID() }), /owning device/);
  const stopped = await phone('stop', { id: second.id });
  assert.equal(stopped.status, 'cancelled');
  const notReclaimed = await mac('claim', { id: second.id, executionId: randomUUID() });
  assert.equal(notReclaimed.status, 'cancelled'); assert.equal(notReclaimed.executionId, null);
});

test('material is separate, receipts durable, approvals bound and projects invalidated', async t => {
  const f = await fixture(t);
  const run = (client: typeof f.mac, op: string, args = {}) => client.request<any>('/v2/hub', 'POST', { op, args });
  const instance = randomUUID(), projectId = randomUUID();
  await run(f.mac, 'advertise', { instance, name: 'Mac', ready: true, projects: [{ id: projectId, name: 'fixture', available: true }] });
  const noteInput = { requestId: randomUUID(), target: 'mac', title: 'Record', text: 'Do NOT execute', attachments: [{ name: 'fixture.txt', mime: 'text/plain', data: 'b2s=' }] };
  const note = await run(f.phone, 'note', noteInput);
  assert.equal(note.state, 'saved');
  assert.equal(f.service.hub.all('command').length, 0);
  await run(f.mac, 'noteState', { id: note.id, state: 'received' });
  await run(f.mac, 'noteState', { id: note.id, state: 'processed' });
  assert.equal((await run(f.mac, 'noteState', { id: note.id, state: 'received' })).state, 'processed');
  const command = await run(f.phone, 'create', { requestId: randomUUID(), target: 'mac', projectId, title: 'Task', prompt: 'test' });
  const req = { id: randomUUID(), sessionId: command.sessionId, kind: 'approval', title: 'Confirm', details: 'fixture only', state: 'pending' };
  await run(f.mac, 'request', req);
  const snapshot = await run(f.phone, 'snapshot');
  assert(snapshot.items.some((i: any) => i.type === 'request' && i.kind === 'approval'));
  await run(f.phone, 'answer', { id: req.id, answer: 'reject' });
  await assert.rejects(run(f.phone, 'answer', { id: req.id, answer: 'allow' }), /Already answered/);
  await run(f.mac, 'request', { ...req, state: 'closed' });
  await assert.rejects(run(f.phone, 'answer', { id: req.id, answer: 'reject' }), /expired/);
  await run(f.mac, 'advertise', { instance, name: 'Mac', ready: true, projects: [] });
  await assert.rejects(run(f.phone, 'send', { sessionId: command.sessionId, requestId: randomUUID(), prompt: 'test' }), /Project unavailable/);
});
