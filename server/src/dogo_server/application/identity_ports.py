"""Identity's small persistence and cryptography boundaries."""

from contextlib import AbstractContextManager
from typing import Protocol

from dogo_server.domain.identity import Account, Device, Principal


class IdentityRepository(Protocol):
    def get_account(self, account_id: str) -> Account | None: ...
    def find_account(self, username: str) -> Account | None: ...
    def add_account(self, account: Account) -> None: ...
    def find_device(self, device_id: str) -> Device | None: ...
    def get_device(self, device_id: str, account_id: str) -> Device | None: ...
    def find_refresh(self, refresh_hash: str) -> Device | None: ...
    def list_devices(self, account_id: str) -> list[Device]: ...
    def save_device(self, device: Device) -> None: ...


class IdentityUnitOfWork(Protocol):
    identities: IdentityRepository


class UnitOfWorkFactory(Protocol):
    def __call__(self, *, write: bool = False) -> AbstractContextManager[IdentityUnitOfWork]: ...


class IdentityCrypto(Protocol):
    def hash_password(self, password: str) -> str: ...
    def verify_password(self, password: str, password_hash: str | None) -> bool: ...
    def hash_token(self, token: str) -> str: ...
    def encode_access(self, principal: Principal, now: int) -> str: ...
    def decode_access(self, token: str) -> Principal: ...
